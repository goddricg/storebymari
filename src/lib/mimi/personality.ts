/**
 * Get the tailor-made personality prompt for Mimi based on current situation.
 */
export function getMimiPersonality(
  situation: MimiSituation,
  options?: PersonalityOptions
): string {
  let situationalPrompt = "";

  switch (situation) {
    case "support":
      situationalPrompt = SUPPORT_PERSONALITY;
      break;
    case "sales":
      situationalPrompt = SALES_PERSONALITY;
      break;
    case "concierge":
      situationalPrompt = CONCIERGE_PERSONALITY;
      break;
    case "admin":
      situationalPrompt = getAdminPersonality(options);
      break;
    default:
      situationalPrompt = CONCIERGE_PERSONALITY;
  }

  return `${situationalPrompt}\n\n${UNIVERSAL_RULES}`;
}

